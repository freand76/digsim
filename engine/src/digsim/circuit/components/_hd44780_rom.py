def _glyphs() -> list[tuple[int, ...]]:
    glyphs: list[tuple[int, ...]] = [(0,) * 8] * 0x10
    for line in _ROM.split("\n"):
        for word in line.split()[:4]:
            glyphs.append(tuple(bytes.fromhex(word)))
    return glyphs


# The glyph of each code, see _ROM
CHARACTER_ROM: list[tuple[int, ...]] = _glyphs()

# The text of the codes that are not ASCII, for HD44780.lines()
_KATAKANA = {code: chr(0xFF61 + code - 0xA1) for code in range(0xA1, 0xE0)}
_SYMBOLS = dict(zip(range(0xE0, 0x100), "αäβεμσρg√⁻jˣ¢£ñöpqθ∞ΩüΣπxy千万円÷ █", strict=True))
TEXT: dict[int, str] = {
    **{code: chr(code) for code in range(0x20, 0x7E)},
    0x5C: "¥",
    0x7E: "→",
    0x7F: "←",
    **_KATAKANA,
    **_SYMBOLS,
}
